"""`agenticreq export` — hand the spec to where enforcement actually happens.

agenticreq never enforces anything itself. These exports are inputs for OPA, Cedar,
or a tool-schema patcher; the policy decision point is theirs.

Input contract for both policy formats (one tool call):
    {"agent_id": str, "tool": str, "args": {...}, "approval": {"granted": bool, "approver": str}}
"""

from __future__ import annotations

import json
import re
from typing import Any

from agenticreq.models.observed import ObservedAgent
from agenticreq.models.spec import AgentSpec

_LIMIT_TO_SCHEMA = {"max": "maximum", "min": "minimum", "max_length": "maxLength", "enum": "enum", "pattern": "pattern"}


def _pkg(agent_id: str) -> str:
    s = re.sub(r"[^a-zA-Z0-9_]", "_", agent_id)
    return s if s[:1].isalpha() else f"a_{s}"


def _allowed(spec: AgentSpec, obs: ObservedAgent | None) -> list[str] | None:
    if spec.role_boundary and spec.role_boundary.allowed_tools:
        return sorted(spec.role_boundary.allowed_tools)
    return None


def _limits(spec: AgentSpec) -> dict[str, dict[str, dict[str, Any]]]:
    out: dict[str, dict[str, dict[str, Any]]] = {}
    for lim in spec.limits or []:
        out.setdefault(lim.tool, {})[lim.arg] = lim.limit.model_dump(exclude_none=True)
    return out


# ------------------------------------------------------------------ OPA / Rego v1
def to_rego(spec: AgentSpec, obs: ObservedAgent | None = None) -> str:
    aid = spec.agent_id or "agent"
    prohibited = {p.tool: p.reason or "" for p in spec.prohibited or [] if p.tool}
    approvals = {
        a.tool: {
            "approver": a.approver,
            "timeout": a.timeout,
            "on_timeout": a.on_timeout or spec.on_approval_timeout or "safe_stop",
        }
        for a in spec.approval_required or []
    }
    allowed = _allowed(spec, obs)
    L = [
        f"# Generated by agenticreq from spec for {aid}. agenticreq does not enforce; OPA does.",
        f"package agenticreq.{_pkg(aid)}",
        "",
        "import rego.v1",
        "",
        "default allow := false",
        "",
        f"prohibited := {json.dumps(prohibited, indent=2, sort_keys=True)}",
        "",
        f"approval_required := {json.dumps(approvals, indent=2, sort_keys=True)}",
        "",
        f"limits := {json.dumps(_limits(spec), indent=2, sort_keys=True)}",
        "",
    ]
    if allowed is not None:
        L += [f"allowed_tools := {json.dumps(allowed)}", ""]
    L += [
        "deny contains msg if {",
        "\treason := prohibited[input.tool]",
        '\tmsg := sprintf("%s is prohibited: %s", [input.tool, reason])',
        "}",
        "",
    ]
    if allowed is not None:
        L += [
            "deny contains msg if {",
            "\tnot input.tool in allowed_tools",
            '\tmsg := sprintf("%s is outside role_boundary", [input.tool])',
            "}",
            "",
        ]
    # every limit first checks the argument's type: a value of the wrong type (an LLM sending "5000" for
    # 5000) is denied as a type mismatch, never compared across types (Rego orders every string above every
    # number, which denies "5" for the wrong reason and would allow a string under a `min`)
    L += [
        "deny contains msg if {",
        "\tsome arg, lim in limits[input.tool]",
        "\tv := input.args[arg]",
        "\texpected := limit_type(lim)",
        "\tnot has_type(v, expected)",
        '\tmsg := sprintf("%s.%s=%v has type %s; the limit needs a %s", [input.tool, arg, v, type_name(v), expected])',
        "}",
        "",
        'limit_type(lim) := "number" if {',
        '\tsome k in ["max", "min"]',
        "\tobject.get(lim, k, null) != null",
        "}",
        "",
        'limit_type(lim) := "string" if {',
        '\tsome k in ["max_length", "pattern"]',
        "\tobject.get(lim, k, null) != null",
        '\tnot "max" in object.keys(lim)',
        '\tnot "min" in object.keys(lim)',
        "}",
        "",
        'has_type(v, "number") if is_number(v)',
        "",
        'has_type(v, "string") if is_string(v)',
        "",
    ]
    for key, op, verb, expr, typ in (
        ("max", ">", "exceeds max", "v", "is_number"),
        ("min", "<", "is below min", "v", "is_number"),
        ("max_length", ">", "is longer than", "count(v)", "is_string"),
    ):
        L += [
            "deny contains msg if {",
            "\tsome arg, lim in limits[input.tool]",
            f'\tbound := object.get(lim, "{key}", null)',
            "\tbound != null",
            "\tv := input.args[arg]",
            f"\t{typ}(v)",
            f"\t{expr} {op} bound",
            f'\tmsg := sprintf("%s.%s=%v {verb} %v", [input.tool, arg, v, bound])',
            "}",
            "",
        ]
    L += [
        "deny contains msg if {",
        "\tsome arg, lim in limits[input.tool]",
        '\tpattern := object.get(lim, "pattern", null)',
        "\tpattern != null",
        "\tv := input.args[arg]",
        "\tis_string(v)",
        "\tnot regex.match(pattern, v)",
        '\tmsg := sprintf("%s.%s=%v does not match %v", [input.tool, arg, v, pattern])',
        "}",
        "",
        "deny contains msg if {",
        "\tsome arg, lim in limits[input.tool]",
        '\tallowed_values := object.get(lim, "enum", null)',
        "\tallowed_values != null",
        "\tv := input.args[arg]",
        "\tnot v in allowed_values",
        '\tmsg := sprintf("%s.%s=%v not in %v", [input.tool, arg, v, allowed_values])',
        "}",
        "",
        "needs_approval contains rule if {",
        "\trule := approval_required[input.tool]",
        "\tnot approved(rule)",
        "}",
        "",
        "approved(rule) if {",
        "\tinput.approval.granted == true",
        "\tinput.approval.approver == rule.approver",
        "}",
        "",
        "allow if {",
        "\tcount(deny) == 0",
        "\tcount(needs_approval) == 0",
        "}",
        "",
    ]
    return "\n".join(L)


# ------------------------------------------------------------------ Cedar
def _cedar_str(s: str) -> str:
    return json.dumps(s)


def _cedar_literal(v: Any) -> str:
    """A Cedar literal of the value's own type: 5 stays a Long, "5" a String (never stringified)."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return str(v)
    return _cedar_str(str(v))


def _limit_checks(lim: Any) -> tuple[list[str], list[str], list[str]]:
    """(violations, conditions the argument must meet, notes) for one limit, over Cedar Longs.

    Cedar has no floats and JSON numbers arrive as Longs, so a fractional bound becomes the nearest whole
    bound on the safe side (max 99.5 -> <= 99, min 0.5 -> >= 1). Comparing a String with a Long is a type
    error; the conditions are therefore also required by the permit, where an error means no permit (deny).
    """
    import math

    a = f"context.args.{lim.arg}" if re.fullmatch(r"[A-Za-z_]\w*", lim.arg) else f"context.args[{_cedar_str(lim.arg)}]"
    L_ = lim.limit
    bad: list[str] = []
    ok: list[str] = []
    notes: list[str] = []
    if L_.max is not None:
        n = math.floor(L_.max)
        bad.append(f"{a} > {n}")
        ok.append(f"{a} <= {n}")
    if L_.min is not None:
        n = math.ceil(L_.min)
        bad.append(f"{a} < {n}")
        ok.append(f"{a} >= {n}")
    if L_.enum is not None:
        values = f"[{', '.join(_cedar_literal(x) for x in L_.enum)}]"
        bad.append(f"!({values}.contains({a}))")
        ok.append(f"{values}.contains({a})")
    for kind in ("max_length", "pattern"):
        if getattr(L_, kind, None) is not None:
            notes.append(
                f"// NOT ENFORCED HERE: {lim.tool}.{lim.arg} {kind} has no Cedar operator; enforce it in the "
                "tool schema (agenticreq export -f schema) or with the OPA export"
            )
    return bad, ok, notes


def to_cedar(spec: AgentSpec, obs: ObservedAgent | None = None) -> str:
    aid = spec.agent_id or "agent"
    P = f"principal == Agent::{_cedar_str(aid)}"
    A = 'action == Action::"call_tool"'
    L = [
        f"// Generated by agenticreq from spec for {aid}. agenticreq does not enforce; Cedar does.",
        "// Entities: Agent, Tool. Action: call_tool. context: { args: Record, approval?: { granted, approver } }",
        "// Limits are required by the permit as well as forbidden: Cedar skips a policy whose evaluation errors,",
        '// so a forbid alone lets a type-confused argument ("5000" for 5000) through. In the permit, the same',
        "// error means no permit applies, and the call is denied.",
        "",
    ]
    guards: list[str] = []
    forbids: list[str] = []
    for lim in spec.limits or []:
        R = f"resource == Tool::{_cedar_str(lim.tool)}"
        has = (
            f"context.args has {lim.arg}"
            if re.fullmatch(r"[A-Za-z_]\w*", lim.arg)
            else f"context.args has {_cedar_str(lim.arg)}"
        )
        bad, ok, notes = _limit_checks(lim)
        forbids += notes
        for i, c in enumerate(bad):
            forbids += [
                f'@id("{aid}.limit.{lim.tool}.{lim.arg}.{i}")',
                f"forbid ({P}, {A}, {R}) when {{ {has} && {c} }};",
                "",
            ]
        if ok:
            guards.append(f"(resource != Tool::{_cedar_str(lim.tool)} || !({has}) || ({' && '.join(ok)}))")
    allowed = _allowed(spec, obs)
    when = (
        [f"[{', '.join(f'Tool::{_cedar_str(t)}' for t in allowed)}].contains(resource)"] if allowed is not None else []
    ) + guards
    if allowed is None:
        L += ["// no role_boundary in spec: permit all tools, constrained by the limits and forbids below"]
    L += [
        f'@id("{aid}.{"role_boundary" if allowed is not None else "default"}")',
        f"permit ({P}, {A}, resource)" + (" when {\n  " + " &&\n  ".join(when) + "\n}" if when else "") + ";",
        "",
    ]
    for p in spec.prohibited or []:
        if p.tool:
            L += [
                f"// {p.reason or 'prohibited'}",
                f'@id("{aid}.prohibited.{p.tool}")',
                f"forbid ({P}, {A}, resource == Tool::{_cedar_str(p.tool)});",
                "",
            ]
    L += forbids
    for ap in spec.approval_required or []:
        R = f"resource == Tool::{_cedar_str(ap.tool)}"
        cond = "context has approval && context.approval.granted == true"
        if ap.approver:
            cond += f" && context.approval.approver == {_cedar_str(ap.approver)}"
        L += [
            f"// approval by {ap.approver}, timeout {ap.timeout} → {ap.on_timeout or 'safe_stop'}",
            f'@id("{aid}.approval.{ap.tool}")',
            f"forbid ({P}, {A}, {R}) unless {{ {cond} }};",
            "",
        ]
    return "\n".join(L)


# ------------------------------------------------------------------ tool-schema constraints
def to_schema_constraints(spec: AgentSpec, obs: ObservedAgent | None = None) -> dict[str, Any]:
    """JSON-schema fragments to merge into each tool's parameters (the model then sees the bound)."""
    out: dict[str, Any] = {"$comment": "generated by agenticreq; merge into tool parameter schemas", "tools": {}}
    for lim in spec.limits or []:
        frag = {
            _LIMIT_TO_SCHEMA[k]: v for k, v in lim.limit.model_dump(exclude_none=True).items() if k in _LIMIT_TO_SCHEMA
        }
        out["tools"].setdefault(lim.tool, {"properties": {}})["properties"][lim.arg] = frag
    if obs:
        for name, t in obs.declared_tools.items():
            if name in out["tools"]:
                out["tools"][name]["code_ref"] = str(t.code_ref) if t.code_ref else None
    return out


FORMATS = {"opa": to_rego, "cedar": to_cedar}
